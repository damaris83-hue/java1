package training;

public class Elseiif {

	
	    public static void main(String[] args) {
	        int score = 777;
	        
	        if(score >= 900){
	            System.out.println("Outstanding");
	        } else if(score >= 750){
	            System.out.println("Excellent");
	        } else if(score >= 550){
	            System.out.println("Good");
	        } else {
	            System.out.println("Average");
	        }
	    }
	}

